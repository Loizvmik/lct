"""`Finding` — единица результата детерминированного аудита (интерфейс
брифа дословно: `Finding(check_id, severity, slide_index, shape_ref,
message, box, fixable, fix_hint)`).

## Severity — три уровня, не два и не пять

Бриф не фиксирует таксономию серьёзности дословно — только само поле.
Три уровня достаточно, чтобы интерфейс мог явно приоритизировать находки
(брифом: "пользователь выбирает, какие из них исправить" — выбор нуждается
в сортировке важности), и не настолько дробно, чтобы граница между
соседними уровнями была произвольной:

- `"critical"` — дефект, который виден или ломает файл при обычном
  просмотре, без анализа: текст физически обрезан краем слайда, контраст
  ниже WCAG (буквы неразличимы на фоне), файл не открывается вовсе, слайд
  на деле подменён скриншотом (ничего не редактируется).
- `"major"` — явное расхождение с дизайн-системой шаблона или с содержанием,
  которое пользователь заметит при чтении, но которое не рушит файл целиком:
  чужой шрифт/кегль/цвет, слайд собран не на макете шаблона, текст не
  поместился в свою рамку, заглушка-плейсхолдер, пустой/почти пустой слайд,
  задвоенный слайд, таблица/график, которым по объёму место в другой форме.
- `"minor"` — отклонение, которое чаще всего требует контекста, чтобы
  решить, брак это или сознательное решение дизайнера: элемент чуть вышел
  из сетки, задел поле, картинка слегка растянута, буллетов/слов чуть
  больше нормы, слайд слегка неидеально заполнен по площади.

Это разбиение соответствует группировке проверок брифа (L/T/D/I) не 1:1 —
внутри одной группы бывают находки разной тяжести (пример: L01 "вышел за
границы" тяжелее L07 "чуть растянута картинка", хотя обе из группы
"вёрстка")."""
from __future__ import annotations
from dataclasses import dataclass
from typing import Literal

from deckforge.ooxml.geometry import Box

Severity = Literal["critical", "major", "minor"]

# Как находку чинить (раздел 13 архитектуры). `"local"`: точечная правка
# фигуры, её делает `audit.autofix` (сдвиг, snap, цвет, контраст, гарнитура,
# легенда, малое переполнение). `"structural"`: локальный патч спрятал бы
# симптом, а не убрал причину (сильное переполнение даже на минимальном
# кегле, сильное наложение, много текста, заполненность далеко от примера);
# нужен другой текст или другая раскладка. `"none"`: чинить нечем или
# незачем (сведения для человека, находки модели по картинке).
Repair = Literal["local", "structural", "none"]


@dataclass(frozen=True)
class Finding:
    check_id: str
    severity: Severity
    slide_index: int | None
    shape_ref: str | None
    message: str
    box: Box | None
    fixable: bool
    fix_hint: str
    # `None` при создании значит "выведи из `fixable`": находки, собранные
    # до задачи R (модель по картинке, тесты, старые вызовы), остаются
    # локальными, если их умели чинить, и не молчат в автопочинке.
    repair: Repair | None = None

    def __post_init__(self) -> None:
        if self.repair is None:
            object.__setattr__(self, "repair", "local" if self.fixable else "none")
