"""Палитра рядов графика — цветные токены шаблона по убыванию веса,
взаимно РАЗЛИЧИМЫЕ (ΔE CIE Lab не ниже порога), при нехватке достроенные
оттенками `brand` (тем же контролем различимости).

Без явной раскраски `python-pptx` отдаёт каждый ряд/точку цвету темы файла
(«accent1..6» из `a:clrScheme`) — на Google-экспортированных шаблонах эта
схема часто заглушка (см. `theme.ThemeInfo.is_stock_office_palette`), и
график выходит в стоковых цветах Office, а не в цветах шаблона (бриф Task
10 дословно). Эта функция строит список hex-цветов, которые `compose/
charts.py` обязан назначить явно каждому ряду/точке.

## Почему одного отбора по весу/насыщенности мало (Task 10 код-ревью,
## находка №2)

Первая версия отбирала цвета по весу и фильтровала по насыщенности/
светлоте (см. `_is_usable_series_color`), но НИКАК не проверяла, отличим
ли отобранный цвет от уже отобранных. На контрольном шаблоне ЛЦТ2026 (не
входит в датасет тестов, проверяется только визуально) это даёт
`#FE095F` и `#FF0053` в одной палитре — оба ярких, оба в разумном
диапазоне светлоты, оба реально частые заливки шаблона, но для глаза это
ОДИН цвет: собственный замер (`deckforge.ooxml.color.delta_e76`) даёт
ΔE76 ≈ 7.0 между ними, при сыром RGB-расстоянии 15 из максимума 441 —
кольцевая диаграмма с такими соседними секторами сливает их в один.

Решение — `MIN_DELTA_E` ниже: кандидат, слишком близкий (в CIE Lab, не в
сыром RGB — см. докстроку `ooxml.color` про то, почему именно Lab)
к уже выбранному цвету палитры, отбрасывается, даже если он тяжелее по
весу следующего кандидата. Различимость проверяется на каждом шаге отбора
— и когда цвета берутся из шаблона, и когда палитра достраивается
оттенками `brand`.
"""
from __future__ import annotations
import colorsys

from deckforge.ooxml.color import darken, delta_e76, lighten
from deckforge.template.usage import Usage

# Сколько цветов рядов нужно максимум одному графику. Запас: у Capacity
# намайненных паттернов (Task 7) `max_series` на трёх учебных шаблонах не
# превышает 4-5, а график презентационного слайда с большим числом рядов
# и так нечитаем на глаз — расширять дальше нет практического смысла.
MAX_CHART_SERIES = 5

# Роли палитры, которые НЕ годятся цветом ряда данных — это тон
# поверхности/текста/поля, а не акцентный цвет, различающий ряды. Именно
# эти роли (наравне с "brand"/"accent"/"danger"/"warning") чаще всего
# оказываются самыми частыми заливками шаблона (фон карточек, текст) —
# без фильтра график красился бы в оттенки серого/белого/чёрного.
_NEUTRAL_ROLES = ("surface", "on_surface", "background", "muted", "border")

# Живой замер на VK Tech без доп. фильтра: два первых цвета по весу —
# #C4C4C4 (серый) и #FEFFFF (почти белый) — ни один из них не совпадает
# БУКВАЛЬНО ни с одной из hex-заливок _NEUTRAL_ROLES (это декоративные
# полутона шаблона, а не сами роли), поэтому фильтр по совпадению строки
# выше их не ловит, хотя визуально это ровно то же самое "нейтральный
# фон/обводка", просто с другим hex. Дополнительный фильтр по HLS: серым
# (низкая насыщенность) и вымытым до почти белого/почти чёрного (крайняя
# светлота) цветам не место среди цветов, которые должны РАЗЛИЧАТЬ ряды на
# графике — они неотличимы от фона/обводки на глаз. Пороги не откалиброваны
# отдельно под каждый шаблон, взяты как типографски разумные "заметно
# серый"/"заметно вымыт" границы.
_MIN_SATURATION = 0.15
_MIN_LIGHTNESS = 0.15
_MAX_LIGHTNESS = 0.85


def _is_usable_series_color(hex_color: str) -> bool:
    h = hex_color.lstrip("#")
    r, g, b = int(h[0:2], 16) / 255, int(h[2:4], 16) / 255, int(h[4:6], 16) / 255
    _hue, lightness, saturation = colorsys.rgb_to_hls(r, g, b)
    return saturation >= _MIN_SATURATION and _MIN_LIGHTNESS <= lightness <= _MAX_LIGHTNESS


# Порог попарной различимости — ΔE76 (CIE Lab), не сырой RGB (см. докстроку
# модуля и `ooxml.color` про то, почему).
#
# Обоснование числа, а не подгонка под файлы (бриф код-ревью, "порог
# обоснуй тем, с какого различия человек уверенно различает два цвета
# рядом"): классический just-noticeable-difference (JND) для ΔE76 между
# двумя ПРИЛЕГАЮЩИМИ образцами цвета под контролируемым освещением —
# около 2.3 (общее место колориметрии, напр. Mokrzycki & Tatol 2011,
# "Color difference Delta E - A survey"; это порог "едва заметно ОПЫТНОМУ
# наблюдателю вплотную", не "уверенно отличит любой человек"). Сектор
# графика/узел схемы на слайде смотрят в куда менее контролируемых
# условиях, чем два образца вплотную под D65: проектор конференц-зала
# искажает цветопередачу, зритель сидит на расстоянии не разглядывая в
# упор, области сравнения — не прилегающие крупные образцы, а маленькие
# несмежные фигуры на графике. Взят распространённый на практике множитель
# запаса над JND (≈ 6-7×, тот же порядок, что и "ΔE > 10 надёжно
# различимо для практических целей" — общее правило категориальных
# палитр, напр. ColorBrewer/картографическая практика) — 15.0, округлое
# число того же порядка, не выведенное подгонкой под три учебных файла.
MIN_DELTA_E = 15.0


def _distinct_enough(candidate: str, chosen: list[str]) -> bool:
    return all(delta_e76(candidate, other) >= MIN_DELTA_E for other in chosen)


# Насколько нужно затемнить/осветлить `brand`, когда цветных токенов
# шаблона не хватило на MAX_CHART_SERIES рядов — числа из брифа задачи
# дословно ("оттенками brand — затемнение и осветление на 45% и 70%"),
# порядок (сначала тёмный, потом светлый на каждом шаге) даёт наибольший
# зрительный контраст между первыми двумя достроенными цветами. Две
# дополнительные ступени (0.20/0.85) — код-ревью, находка №2: с проверкой
# различимости включённой, какая-то из четырёх брифовых ступеней может
# оказаться слишком близкой (ΔE) к уже выбранному цвету и быть отброшена —
# без запасных ступеней достройка могла бы недобрать рядов там, где раньше
# (без проверки различимости) добирала их вслепую.
_TINT_STEPS: tuple[tuple[str, float], ...] = (
    ("dark", 0.45), ("light", 0.45), ("dark", 0.70), ("light", 0.70),
    ("dark", 0.20), ("light", 0.20), ("dark", 0.85), ("light", 0.85),
)


def build_chart_series(
    usage: Usage, palette_roles: dict[str, str], *, max_series: int = MAX_CHART_SERIES,
) -> list[str]:
    """Цвета рядов/точек графика — цветные заливки шаблона (`Usage.fill`)
    по убыванию частоты употребления, без нейтральных ролей палитры,
    ПОПАРНО РАЗЛИЧИМЫЕ (ΔE76 не ниже `MIN_DELTA_E`, см. докстроку модуля),
    достроенные оттенками `brand`, если цветных токенов не хватило (с тем
    же контролем различимости)."""
    neutral_hexes = {
        v.upper() for role, v in palette_roles.items() if role in _NEUTRAL_ROLES and v
    }
    weight: dict[str, int] = {}
    for color, count in usage.fill.items():
        hex_ = getattr(color, "hex", None)
        if not hex_:
            continue
        hex_upper = hex_.upper()
        if hex_upper in neutral_hexes or not _is_usable_series_color(hex_upper):
            continue
        weight[hex_upper] = weight.get(hex_upper, 0) + count

    ordered = [hex_ for hex_, _ in sorted(weight.items(), key=lambda kv: (-kv[1], kv[0]))]

    series: list[str] = []
    for hex_ in ordered:
        if len(series) >= max_series:
            break
        if _distinct_enough(hex_, series):
            series.append(hex_)

    brand = palette_roles.get("brand")
    if brand:
        for direction, amount in _TINT_STEPS:
            if len(series) >= max_series:
                break
            tint = darken(brand, amount) if direction == "dark" else lighten(brand, amount)
            tint_upper = tint.upper()
            if _distinct_enough(tint_upper, series):
                series.append(tint)

    return series
