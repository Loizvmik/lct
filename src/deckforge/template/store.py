"""Где лежит разобранный шаблон.

Разбор шаблона — дорогая операция (обращения к модели за видом раскладки,
десятки секунд), и делается она один раз на файл: ключ считается от
СОДЕРЖИМОГО .pptx, поэтому та же презентация, загруженная второй раз, берёт
готовый разбор и не стоит ничего.

Хранилище вынесено за отдельный интерфейс, чтобы тот же разбор мог лежать
не только рядом с репозиторием, но и в общем месте на всю установку (S3 и
подобное): один шаблон, разобранный однажды, годится всем запускам и всем
машинам. Реализация здесь пока одна — каталог на диске; вторая добавляется
классом с теми же двумя методами, остальной код о ней не узнает.

**Ключ включает версию разбора, а не только отпечаток файла.** Это не
формальность: 23 сентября 2026 мы дважды обожглись на том, что запись,
сделанная старым кодом, молча отдавалась новому. Сначала разбор без модели
переиспользовался, когда ключ модели уже появился, — половина раскладок
шаблона оставалась неразобранной. Потом изменился смысл поля вместимости,
и старые записи отдавали старые числа, из-за которых слайды выходили
заполненными на два процента. Локально это чинится чисткой каталога; в
общем хранилище, которое переживает выкатку новой версии, такая запись
живёт годами. Версия в ключе делает ошибку невозможной: новый код просто
не увидит чужих записей.
"""
from __future__ import annotations
import hashlib
from pathlib import Path
from typing import Protocol


def profile_key(template_bytes: bytes, schema_version: int) -> str:
    """Ключ разбора: отпечаток файла шаблона плюс версия схемы разбора.

    Отпечаток берётся от БАЙТОВ файла, не от имени и не от времени
    изменения: тот же шаблон под другим именем — тот же разбор, а
    пересохранённый заново — другой, даже если выглядит так же."""
    fingerprint = hashlib.sha256(template_bytes).hexdigest()
    return f"{fingerprint}-v{schema_version}"


class ProfileStore(Protocol):
    """Два метода, которых хватает для любого хранилища разборов."""

    def get(self, key: str) -> str | None:
        """Текст разбора по ключу или `None`, если его там нет."""

    def put(self, key: str, text: str) -> None:
        """Положить разбор под ключом. Запись не обязана быть атомарной —
        два одновременных разбора одного шаблона дают одинаковый текст."""


class LocalProfileStore:
    """Каталог на диске. Поведение то же, что было до появления интерфейса.

    Ошибки чтения и записи глотаются намеренно: кеш — ускорение, а не
    источник правды. Нет прав на каталог, диск полон, файл повреждён —
    разбор просто выполняется заново, а не роняет генерацию."""

    def __init__(self, directory: Path) -> None:
        self.directory = Path(directory)

    def get(self, key: str) -> str | None:
        path = self.directory / f"{key}.json"
        try:
            return path.read_text(encoding="utf-8")
        except Exception:
            return None

    def put(self, key: str, text: str) -> None:
        try:
            self.directory.mkdir(parents=True, exist_ok=True)
            (self.directory / f"{key}.json").write_text(text, encoding="utf-8")
        except Exception:
            pass
